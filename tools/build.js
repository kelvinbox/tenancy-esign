#!/usr/bin/env node
/*
 * Copies the shared core and template into the Apps Script folder, so the live backend runs
 * exactly the same rules as the demo and the tests. Run after changing docs/js/core.js or
 * docs/js/agreement-template.js:  npm run build
 */
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const banner = '// GENERATED by tools/build.js from {src}. Do not edit here; edit {src} and run "npm run build".\n';
const pairs = [
  ['docs/js/core.js', 'apps-script/Core.js'],
  ['docs/js/agreement-template.js', 'apps-script/Template.js']
];

function generated(src) {
  return banner.replace(/\{src\}/g, src) + fs.readFileSync(path.join(root, src), 'utf8');
}

if (require.main === module) {
  for (const [src, dest] of pairs) {
    fs.writeFileSync(path.join(root, dest), generated(src));
    console.log(`${src} -> ${dest}`);
  }
}

module.exports = { pairs, generated, root };
